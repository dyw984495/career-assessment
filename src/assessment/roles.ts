// 岗位构造函数
const mkRole = (
  name: string,
  icon: string,
  interest: InterestScores,
  personality: PersonalityScores,
    desc: string,
    _tasks: string[], // 已废弃，典型任务现从 TASK_DETAILS 获取
    school: string,
  skills: string[],
  salary: string[],
  industries: string[],
  companies: string[],
): Role => {
  const internshipRequirement = INTERNSHIP_REQUIREMENTS[name]
  if (!internshipRequirement) {
    throw new Error(`[roles] 缺少实习门槛文案（岗位库.xlsx）：${name}`)
  }
  const taskDetails = TASK_DETAILS[name]
  if (!taskDetails) {
    throw new Error(`[roles] 缺少任务详情：${name}`)
  }
  return {
    name,
    icon,
    interest,
    personality,
    desc,
    tasks: taskDetails, // 直接使用 TASK_DETAILS 作为 tasks，与 Excel 保持一致
    taskDetails,
    school,
    skills,
    salary,
    industries,
    companies,
    internshipRequirement,
  }
}

